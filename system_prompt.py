def _known_candidate_block(candidate_profile: dict | None) -> str:
    known = {k: v for k, v in (candidate_profile or {}).items() if v}
    if not known:
        return "Пока ничего не известно — это начало диалога с кандидатом."
    lines = [f"- {_PROFILE_LABELS.get(k, k)}: {v}" for k, v in known.items()]
    return "\n".join(lines)


